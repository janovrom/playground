using System.Collections.Immutable;
using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace ModularMonolith.Generators;

/// <summary>Generates Host registration, typed clients, and worker entry points.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class WorkerSourceGenerator : IIncrementalGenerator
{
    private static readonly SymbolDisplayFormat FullyQualifiedNullableFormat =
        SymbolDisplayFormat.FullyQualifiedFormat.AddMiscellaneousOptions(
            SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);
    private const string WorkerModuleAttributeName = "ModularMonolith.Contracts.WorkerModuleAttribute";
    private const string WorkerProxyRouteAttributeName = "ModularMonolith.Contracts.WorkerProxyRouteAttribute";
    private const string WorkerClientAttributeName = "ModularMonolith.Contracts.WorkerClientAttribute";
    private const string WorkerClientOperationAttributeName = "ModularMonolith.Contracts.WorkerClientOperationAttribute";
    private const string WorkerModuleInterfaceName = "ModularMonolith.Worker.Hosting.IWorkerModule";
    /// <summary>Registers the source-generation transform with the compilation.</summary>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var compilations = context.CompilationProvider.Select(
            static (compilation, _) => CreateModel(compilation));
        context.RegisterSourceOutput(compilations, static (context, model) =>
        {
            if (model is null)
            {
                return;
            }

            foreach (var source in model.Sources)
            {
                context.AddSource(source.HintName, source.Content);
            }

            foreach (var diagnostic in model.Diagnostics)
            {
                context.ReportDiagnostic(diagnostic);
            }
        });
    }

    private static GeneratorModel? CreateModel(Compilation compilation)
    {
        var diagnostics = ImmutableArray.CreateBuilder<Diagnostic>();
        var workerModules = GetCurrentTypes(compilation)
            .Where(type => Implements(type, WorkerModuleInterfaceName))
            .Where(type => !type.IsAbstract && type.TypeKind == TypeKind.Class)
            .OrderBy(type => type.ToDisplayString(), StringComparer.Ordinal)
            .ToArray();
        if (workerModules.Length > 1)
        {
            diagnostics.Add(Diagnostic.Create(
                Diagnostics.MultipleWorkerModules,
                workerModules[1].Locations.FirstOrDefault(),
                workerModules.Length,
                compilation.AssemblyName));
        }

        var sources = ImmutableArray.CreateBuilder<GeneratedSource>();
        if (workerModules.Length == 1)
        {
            sources.Add(GenerateWorkerEntryPoint(workerModules[0]));
        }
        else if (workerModules.Length == 0
                 && !string.Equals(compilation.AssemblyName, "ModularMonolith.Host", StringComparison.Ordinal)
                 && compilation.GetTypeByMetadataName(WorkerModuleInterfaceName) is not null)
        {
            diagnostics.Add(Diagnostic.Create(
                Diagnostics.MissingWorkerModule,
                Location.None,
                compilation.AssemblyName));
        }

        if (string.Equals(compilation.AssemblyName, "ModularMonolith.Host", StringComparison.Ordinal))
        {
            var modules = DiscoverModules(compilation, diagnostics);
            var clients = DiscoverClients(compilation, modules, diagnostics);
            sources.Add(GenerateHostRegistration(compilation, modules, clients));
        }

        if (sources.Count == 0 && diagnostics.Count == 0)
        {
            return null;
        }

        return new GeneratorModel(sources.ToImmutable(), diagnostics.ToImmutable());
    }

    private static GeneratedSource GenerateWorkerEntryPoint(INamedTypeSymbol module)
    {
        var moduleType = module.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var moduleName = module.Name;
        var content = $$"""
            // <auto-generated />
            #nullable enable

            namespace ModularMonolith.Generated;

            internal static class {{moduleName}}Program
            {
                public static Task Main(string[] args)
                    => ModularMonolith.Worker.Hosting.WorkerHost.RunAsync(
                        args,
                        new {{moduleType}}());
            }
            """;
        return new GeneratedSource($"{moduleName}Program.g.cs", content);
    }

    private static GeneratedSource GenerateHostRegistration(
        Compilation compilation,
        ImmutableArray<ModuleModel> modules,
        ImmutableArray<ClientModel> clients)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        builder.AppendLine("using System.Net.Http.Json;");
        builder.AppendLine("using ModularMonolith.Abstractions;");
        builder.AppendLine("using ModularMonolith.Contracts;");
        builder.AppendLine("using ModularMonolith.Host.Modules;");
        builder.AppendLine();
        builder.AppendLine("namespace ModularMonolith.Host;");
        builder.AppendLine();
        builder.AppendLine("internal static class GeneratedModuleServiceCollectionExtensions");
        builder.AppendLine("{");
        builder.AppendLine("    public static IServiceCollection AddGeneratedWorkerModules(this IServiceCollection services)");
        builder.AppendLine("    {");

        foreach (var module in modules.OrderBy(item => item.Name, StringComparer.Ordinal))
        {
            builder.Append("        var ");
            builder.Append(module.VariableName);
            builder.Append(" = new HostModuleDescriptor(");
            builder.AppendLine();
            builder.Append("            ");
            AppendString(builder, module.Name);
            builder.AppendLine(",");
            builder.Append("            ");
            AppendString(builder, module.WorkerProject);
            builder.AppendLine(",");
            builder.Append("            ");
            AppendString(builder, module.ConfigSection);
            builder.AppendLine(",");

            builder.AppendLine("            new JobLimits(),");

            builder.AppendLine("            [");
            foreach (var route in module.Routes.OrderBy(item => item.PublicPath, StringComparer.Ordinal))
            {
                builder.Append("                new WorkerProxyRouteDescriptor(");
                AppendString(builder, route.PublicPath);
                builder.Append(", ");
                AppendString(builder, route.DestinationPath);
                builder.AppendLine("),");
            }

            builder.AppendLine("            ],");
            builder.AppendLine("            _ => []);");

            builder.Append("        services.AddHostModuleDescriptor(");
            builder.Append(module.VariableName);
            builder.AppendLine(");");
        }

        foreach (var client in clients.OrderBy(item => item.InterfaceName, StringComparer.Ordinal))
        {
            builder.AppendLine();
            builder.Append("        services.AddSingleton<");
            builder.Append(client.InterfaceName);
            builder.AppendLine(">(serviceProvider =>");
            builder.Append("            new ");
            builder.Append(client.ImplementationName);
            builder.Append("(");
            builder.Append("serviceProvider.GetRequiredService<IWorkerClientFactory>().Create(");
            AppendString(builder, client.Module.Name);
            builder.Append(", ");
            AppendString(builder, client.Module.ConfigSection);
            builder.AppendLine(")));");
        }

        builder.AppendLine("        return services;");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        builder.AppendLine();
        builder.AppendLine();

        foreach (var client in clients.OrderBy(item => item.InterfaceName, StringComparer.Ordinal))
        {
            AppendClient(builder, client);
        }

        return new GeneratedSource("GeneratedWorkerModules.g.cs", builder.ToString());
    }

    private static void AppendClient(StringBuilder builder, ClientModel client)
    {
        builder.Append("internal sealed class ");
        builder.Append(client.ImplementationName);
        builder.Append("(HttpClient httpClient) : ");
        builder.Append(client.InterfaceName);
        builder.AppendLine(", IDisposable");
        builder.AppendLine("{");
        foreach (var operation in client.Operations)
        {
            AppendOperation(builder, operation);
        }

        builder.AppendLine("    public void Dispose() => httpClient.Dispose();");
        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static void AppendOperation(StringBuilder builder, OperationModel operation)
    {
        builder.Append("    public async ");
        builder.Append(operation.ReturnType);
        builder.Append(' ');
        builder.Append(operation.Name);
        builder.Append('(');
        builder.Append(string.Join(
            ", ",
            operation.Parameters.Select(parameter => $"{parameter.Type} {parameter.Name}")));
        builder.AppendLine(")");
        builder.AppendLine("    {");

        var path = operation.Path;
        foreach (var parameter in operation.Parameters
                     .Where(item => path.IndexOf($"{{{item.Name}}}", StringComparison.Ordinal) >= 0))
        {
            path = path.Replace(
                $"{{{parameter.Name}}}",
                $"{{Uri.EscapeDataString({parameter.Name}.ToString())}}");
        }

        var isInterpolated = path.Contains("{Uri.");
        builder.Append("        var path = ");
        if (isInterpolated)
        {
            builder.Append('$');
        }

        AppendString(builder, path);
        builder.AppendLine(";");

        if (operation.HttpMethod == "GET")
        {
            builder.Append("        using var response = await httpClient.GetAsync(path, cancellationToken)");
            builder.AppendLine(";");
        }
        else
        {
            var body = operation.Parameters.FirstOrDefault(parameter =>
                !parameter.IsCancellationToken
                && operation.Path.IndexOf($"{{{parameter.Name}}}", StringComparison.Ordinal) < 0);
            if (body is null)
            {
                throw new InvalidOperationException($"Operation '{operation.Name}' requires a request body.");
            }

            if (operation.RequestKind == 1)
            {
                builder.Append("        using var content = System.Net.Http.Json.JsonContent.Create(");
                builder.Append(body.Name);
                builder.Append(", ContractJsonContext.Default.");
                builder.Append(GetTypeInfoProperty(body.Type));
                builder.AppendLine(");");
            }
            else if (operation.RequestKind == 2)
            {
                builder.Append("        using var content = new ByteArrayContent(");
                builder.Append(body.Name);
                builder.AppendLine(");");
                if (operation.RequestContentType is not null)
                {
                    builder.Append("        content.Headers.ContentType = new System.Net.Http.Headers.MediaTypeHeaderValue(");
                    AppendString(builder, operation.RequestContentType);
                    builder.AppendLine(");");
                }
            }
            else
            {
                throw new InvalidOperationException($"Operation '{operation.Name}' has an unsupported request body.");
            }

            builder.Append("        using var response = await httpClient.");
            builder.Append(CultureInfo.InvariantCulture.TextInfo.ToTitleCase(operation.HttpMethod.ToLowerInvariant()));
            builder.Append("Async(path, content, cancellationToken);");
            builder.AppendLine();
        }

        if (operation.TreatNotFoundAsNull)
        {
            builder.AppendLine("        if (response.StatusCode == System.Net.HttpStatusCode.NotFound)");
            builder.AppendLine("        {");
            builder.AppendLine("            return null;");
            builder.AppendLine("        }");
        }

        builder.AppendLine("        response.EnsureSuccessStatusCode();");
        switch (operation.ResponseKind)
        {
            case 2:
                builder.AppendLine("        return await response.Content.ReadAsStringAsync(cancellationToken);");
                break;
            case 3:
                builder.AppendLine("        return await response.Content.ReadAsByteArrayAsync(cancellationToken);");
                break;
            case 1:
                builder.Append("        return (await response.Content.ReadFromJsonAsync(");
                builder.Append("ContractJsonContext.Default.");
                builder.Append(operation.ResponseTypeInfoProperty);
                builder.AppendLine(", cancellationToken))!;");
                break;
            default:
                break;
        }

        builder.AppendLine("    }");
        builder.AppendLine();
    }

    private static ImmutableArray<ModuleModel> DiscoverModules(
        Compilation compilation,
        ImmutableArray<Diagnostic>.Builder diagnostics)
    {
        var modules = ImmutableArray.CreateBuilder<ModuleModel>();
        foreach (var type in GetReferencedTypes(compilation))
        {
            var moduleAttribute = type.GetAttributes()
                .FirstOrDefault(attribute => attribute.AttributeClass?.ToDisplayString() == WorkerModuleAttributeName);
            if (moduleAttribute is null)
            {
                continue;
            }

            var values = moduleAttribute.ConstructorArguments;
            if (values.Length != 3
                || values.Any(value => value.Value is not string || string.IsNullOrWhiteSpace((string)value.Value)))
            {
                diagnostics.Add(Diagnostic.Create(
                    Diagnostics.InvalidModuleDeclaration,
                    type.Locations.FirstOrDefault(),
                    type.ToDisplayString()));
                continue;
            }

            var routes = type.GetAttributes()
                .Where(attribute => attribute.AttributeClass?.ToDisplayString() == WorkerProxyRouteAttributeName)
                .Select(attribute => new RouteModel(
                    (string)attribute.ConstructorArguments[0].Value!,
                    (string)attribute.ConstructorArguments[1].Value!))
                .ToArray();
            modules.Add(new ModuleModel(
                (string)values[0].Value!,
                (string)values[1].Value!,
                (string)values[2].Value!,
                routes));
        }

        foreach (var duplicate in modules.GroupBy(module => module.Name, StringComparer.Ordinal)
                     .Where(group => group.Count() > 1))
        {
            diagnostics.Add(Diagnostic.Create(
                Diagnostics.DuplicateModule,
                Location.None,
                duplicate.Key));
        }

        return modules.ToImmutable();
    }

    private static ImmutableArray<ClientModel> DiscoverClients(
        Compilation compilation,
        ImmutableArray<ModuleModel> modules,
        ImmutableArray<Diagnostic>.Builder diagnostics)
    {
        var moduleMap = modules.ToDictionary(module => module.Name, StringComparer.Ordinal);
        var clients = ImmutableArray.CreateBuilder<ClientModel>();
        foreach (var type in GetReferencedTypes(compilation).Where(type => type.TypeKind == TypeKind.Interface))
        {
            var clientAttribute = type.GetAttributes()
                .FirstOrDefault(attribute => attribute.AttributeClass?.ToDisplayString() == WorkerClientAttributeName);
            if (clientAttribute is null)
            {
                continue;
            }

            var moduleName = (string)clientAttribute.ConstructorArguments[0].Value!;
            if (!moduleMap.TryGetValue(moduleName, out var module))
            {
                diagnostics.Add(Diagnostic.Create(
                    Diagnostics.UnknownClientModule,
                    type.Locations.FirstOrDefault(),
                    moduleName,
                    type.ToDisplayString()));
                continue;
            }

            var operations = ImmutableArray.CreateBuilder<OperationModel>();
            foreach (var method in type.GetMembers().OfType<IMethodSymbol>()
                         .Where(method => method.MethodKind == MethodKind.Ordinary)
                         .OrderBy(method => method.Name, StringComparer.Ordinal))
            {
                var operationAttribute = method.GetAttributes()
                    .FirstOrDefault(attribute =>
                        attribute.AttributeClass?.ToDisplayString() == WorkerClientOperationAttributeName);
                if (operationAttribute is null)
                {
                    diagnostics.Add(Diagnostic.Create(
                        Diagnostics.MissingOperationAttribute,
                        method.Locations.FirstOrDefault(),
                        method.Name,
                        type.ToDisplayString()));
                    continue;
                }

                var cancellationToken = method.Parameters.SingleOrDefault(parameter =>
                    parameter.Type.ToDisplayString() == "System.Threading.CancellationToken");
                var httpMethod = (string)operationAttribute.ConstructorArguments[0].Value!;
                var path = (string)operationAttribute.ConstructorArguments[1].Value!;
                var requestKind = (int)operationAttribute.ConstructorArguments[2].Value!;
                var responseKind = (int)operationAttribute.ConstructorArguments[3].Value!;
                var returnTask = method.ReturnType as INamedTypeSymbol;
                var isGenericTask = returnTask?.IsGenericType == true
                    && returnTask?.Name == "Task"
                    && returnTask?.ContainingNamespace.ToDisplayString() == "System.Threading.Tasks";
                var responseType = isGenericTask ? returnTask!.TypeArguments[0] : null;
                var requestContentType = operationAttribute.NamedArguments
                    .FirstOrDefault(argument => argument.Key == "RequestContentType")
                    .Value.Value as string;
                var treatNotFoundAsNull = operationAttribute.NamedArguments
                    .FirstOrDefault(argument => argument.Key == "TreatNotFoundAsNull")
                    .Value.Value as bool? ?? false;
                if (cancellationToken is null)
                {
                    diagnostics.Add(Diagnostic.Create(
                        Diagnostics.MissingCancellationToken,
                        method.Locations.FirstOrDefault(),
                        method.Name));
                    continue;
                }

                var httpMethodName = httpMethod.ToUpperInvariant();
                var supportedMethod = httpMethodName is "GET" or "POST" or "PUT" or "DELETE" or "PATCH";
                var supportedRequest = requestKind is 0 or 1 or 2;
                var supportedResponse = responseKind is 0 or 1 or 2 or 3;
                var bodyCount = method.Parameters.Count(parameter =>
                    !SymbolEqualityComparer.Default.Equals(parameter, cancellationToken)
                    && path.IndexOf($"{{{parameter.Name}}}", StringComparison.Ordinal) < 0);
                var validBody = requestKind == 0 ? bodyCount == 0 : bodyCount == 1;
                var validReturn = responseKind == 0
                    ? !isGenericTask
                    : isGenericTask && responseType is not null;
                if (!supportedMethod
                    || !path.StartsWith("/", StringComparison.Ordinal)
                    || !supportedRequest
                    || !supportedResponse
                    || !validBody
                    || !validReturn)
                {
                    diagnostics.Add(Diagnostic.Create(
                        Diagnostics.UnsupportedClientOperation,
                        method.Locations.FirstOrDefault(),
                        method.Name,
                        type.ToDisplayString()));
                    continue;
                }

                operations.Add(new OperationModel(
                    method.Name,
                    method.ReturnType.ToDisplayString(FullyQualifiedNullableFormat),
                    httpMethodName,
                    path,
                    requestKind,
                    responseKind,
                    requestContentType,
                    treatNotFoundAsNull,
                    responseType is null ? null : GetTypeInfoProperty(
                        responseType.ToDisplayString(FullyQualifiedNullableFormat)),
                    method.Parameters.Select(parameter => new ParameterModel(
                        parameter.Name,
                        parameter.Type.ToDisplayString(FullyQualifiedNullableFormat),
                        parameter.Type.ToDisplayString() == "System.Threading.CancellationToken")).ToArray()));
            }

            clients.Add(new ClientModel(
                type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                StripInterfacePrefix(type.Name),
                module,
                operations.ToImmutable()));
        }

        return clients.ToImmutable();
    }

    private static IEnumerable<INamedTypeSymbol> GetCurrentTypes(Compilation compilation)
        => GetAllTypes(compilation.GlobalNamespace)
            .Where(type => SymbolEqualityComparer.Default.Equals(type.ContainingAssembly, compilation.Assembly));

    private static IEnumerable<INamedTypeSymbol> GetReferencedTypes(Compilation compilation)
        => GetAllTypes(compilation.GlobalNamespace)
            .Where(type => !SymbolEqualityComparer.Default.Equals(type.ContainingAssembly, compilation.Assembly));

    private static IEnumerable<INamedTypeSymbol> GetAllTypes(INamespaceSymbol namespaceSymbol)
    {
        foreach (var member in namespaceSymbol.GetMembers())
        {
            if (member is INamespaceSymbol childNamespace)
            {
                foreach (var nested in GetAllTypes(childNamespace))
                {
                    yield return nested;
                }
            }
            else if (member is INamedTypeSymbol type)
            {
                yield return type;
                foreach (var nested in type.GetTypeMembers())
                {
                    yield return nested;
                }
            }
        }
    }

    private static bool Implements(INamedTypeSymbol type, string interfaceName)
        => type.AllInterfaces.Any(item => item.ToDisplayString() == interfaceName);

    private static string ToIdentifier(string moduleName)
        => string.Concat(moduleName.Split('-').Select(item =>
            char.ToUpperInvariant(item[0]) + item.Substring(1)));

    private static string StripInterfacePrefix(string name)
        => name.Length > 1 && name[0] == 'I' && char.IsUpper(name[1])
            ? name.Substring(1)
            : name;

    private static string GetTypeInfoProperty(string typeName)
    {
        var name = typeName;
        var generic = name.IndexOf('<');
        if (generic >= 0)
        {
            name = name.Substring(0, generic);
        }

        var dot = name.LastIndexOf('.');
        return dot >= 0 ? name.Substring(dot + 1) : name.TrimStart('@');
    }

    private static void AppendString(StringBuilder builder, string value)
    {
        builder.Append('"');
        builder.Append(value.Replace("\\", "\\\\").Replace("\"", "\\\""));
        builder.Append('"');
    }

    private static class Diagnostics
    {
        public static readonly DiagnosticDescriptor MultipleWorkerModules = new(
            "MMG001",
            "Multiple worker modules found",
            "Compilation '{1}' contains {0} IWorkerModule implementations; exactly one is allowed",
            "Worker modules",
            DiagnosticSeverity.Error,
            true);

        public static readonly DiagnosticDescriptor InvalidModuleDeclaration = new(
            "MMG002",
            "Invalid module declaration",
            "Module declaration '{0}' must provide non-empty name, worker project, and configuration section values",
            "Modules",
            DiagnosticSeverity.Error,
            true);

        public static readonly DiagnosticDescriptor DuplicateModule = new(
            "MMG003",
            "Duplicate module declaration",
            "Module name '{0}' is declared more than once",
            "Modules",
            DiagnosticSeverity.Error,
            true);

        public static readonly DiagnosticDescriptor UnknownClientModule = new(
            "MMG004",
            "Unknown client module",
            "Client '{1}' refers to module '{0}', which has no declaration",
            "Clients",
            DiagnosticSeverity.Error,
            true);

        public static readonly DiagnosticDescriptor MissingOperationAttribute = new(
            "MMG005",
            "Missing client operation metadata",
            "Client method '{0}' on '{1}' must declare WorkerClientOperationAttribute",
            "Clients",
            DiagnosticSeverity.Error,
            true);

        public static readonly DiagnosticDescriptor MissingCancellationToken = new(
            "MMG006",
            "Missing cancellation token",
            "Client method '{0}' must accept a CancellationToken parameter",
            "Clients",
            DiagnosticSeverity.Error,
            true);

        public static readonly DiagnosticDescriptor UnsupportedClientOperation = new(
            "MMG007",
            "Unsupported client operation",
            "Client method '{0}' on '{1}' has an unsupported HTTP, body, path, or return shape",
            "Clients",
            DiagnosticSeverity.Error,
            true);

        public static readonly DiagnosticDescriptor MissingWorkerModule = new(
            "MMG008",
            "Worker module not found",
            "Compilation '{0}' references Worker.Hosting but contains no IWorkerModule implementation",
            "Worker modules",
            DiagnosticSeverity.Error,
            true);
    }

    private sealed class GeneratorModel
    {
        public GeneratorModel(
            ImmutableArray<GeneratedSource> sources,
            ImmutableArray<Diagnostic> diagnostics)
        {
            Sources = sources;
            Diagnostics = diagnostics;
        }

        public ImmutableArray<GeneratedSource> Sources { get; }

        public ImmutableArray<Diagnostic> Diagnostics { get; }
    }

    private sealed class GeneratedSource
    {
        public GeneratedSource(string hintName, string content)
        {
            HintName = hintName;
            Content = content;
        }

        public string HintName { get; }

        public string Content { get; }
    }

    private sealed class ModuleModel
    {
        public ModuleModel(string name, string workerProject, string configSection, RouteModel[] routes)
        {
            Name = name;
            WorkerProject = workerProject;
            ConfigSection = configSection;
            Routes = routes;
            VariableName = ToIdentifier(name) + "Descriptor";
        }

        public string Name { get; }

        public string WorkerProject { get; }

        public string ConfigSection { get; }

        public RouteModel[] Routes { get; }

        public string VariableName { get; }
    }

    private sealed class RouteModel
    {
        public RouteModel(string publicPath, string destinationPath)
        {
            PublicPath = publicPath;
            DestinationPath = destinationPath;
        }

        public string PublicPath { get; }

        public string DestinationPath { get; }
    }

    private sealed class ClientModel
    {
        public ClientModel(
            string interfaceName,
            string implementationName,
            ModuleModel module,
            ImmutableArray<OperationModel> operations)
        {
            InterfaceName = interfaceName;
            ImplementationName = implementationName;
            Module = module;
            Operations = operations;
        }

        public string InterfaceName { get; }

        public string ImplementationName { get; }

        public ModuleModel Module { get; }

        public ImmutableArray<OperationModel> Operations { get; }
    }

    private sealed class OperationModel
    {
        public OperationModel(
            string name,
            string returnType,
            string httpMethod,
            string path,
            int requestKind,
            int responseKind,
            string? requestContentType,
            bool treatNotFoundAsNull,
            string? responseTypeInfoProperty,
            ParameterModel[] parameters)
        {
            Name = name;
            ReturnType = returnType;
            HttpMethod = httpMethod;
            Path = path;
            RequestKind = requestKind;
            ResponseKind = responseKind;
            RequestContentType = requestContentType;
            TreatNotFoundAsNull = treatNotFoundAsNull;
            ResponseTypeInfoProperty = responseTypeInfoProperty;
            Parameters = parameters;
        }

        public string Name { get; }

        public string ReturnType { get; }

        public string HttpMethod { get; }

        public string Path { get; }

        public int RequestKind { get; }

        public int ResponseKind { get; }

        public string? RequestContentType { get; }

        public bool TreatNotFoundAsNull { get; }

        public string? ResponseTypeInfoProperty { get; }

        public ParameterModel[] Parameters { get; }
    }

    private sealed class ParameterModel
    {
        public ParameterModel(string name, string type, bool isCancellationToken)
        {
            Name = name;
            Type = type;
            IsCancellationToken = isCancellationToken;
        }

        public string Name { get; }

        public string Type { get; }

        public bool IsCancellationToken { get; }
    }
}
